# Generates src/font.h with the original game's font (A.FLOWY.bin, the Apple II FONT, in 1-source-files/fonts of the
# reference source): characters 32..127, 8 bytes each, 7 dots wide with bit 0 on the left (bit 7 is
# the Apple palette bit and is not used). Here bit 7 is the leftmost dot (to dump directly).
# Usage: python3 tools/gen_font.py [A.FLOWY.bin] [src/font.h]   (by default, from ELITE_SRC/../fonts)
import os, sys
import elitesrc
src = sys.argv[1] if len(sys.argv) > 1 else os.path.join(elitesrc.SRC_DIR, '..', 'fonts', 'A.FLOWY.bin')
dst = sys.argv[2] if len(sys.argv) > 2 else 'src/font.h'
d = open(src, 'rb').read()
assert len(d) == 768, len(d)
def rev(b): return int('{:08b}'.format(b & 0x7F)[::-1], 2)
out = ["/* Generated by tools/gen_font.py from A.FLOWY.bin (the Elite Apple II font, FONT). ASCII 32..127, bit7 = left dot. */",
       "static const u8 font8x8[96][8] = {"]
for c in range(32, 128):
    v = [rev(x) for x in d[(c - 32) * 8:(c - 31) * 8]]
    out.append("    {%s}, /* %d %s */" % (','.join('0x%02X' % x for x in v), c, repr(chr(c)) if c < 127 else 'DEL'))
out.append("};")
open(dst, 'w').write('\n'.join(out) + '\n')
print(dst, 'desde', src)
