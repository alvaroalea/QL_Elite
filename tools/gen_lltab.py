#!/usr/bin/env python3
"""Generates src/ql_lltab.asm: the log, logL and alogh tables of src/math_tables.h interleaved (4 bytes per entry: log, logL, alogh, 0)
so that ql_ll9.asm reads them with ONE base register and index i*4 (the 68000 indexed mode only has an 8-bit displacement)."""
import re, sys
src = open('src/math_tables.h').read()
def arr(name):
    m = re.search(r'em_%s\[256\]\s*=\s*\{(.*?)\};' % name, src, re.S)
    v = [int(x, 0) for x in re.findall(r'0x[0-9A-Fa-f]+|\d+', m.group(1))]
    assert len(v) == 256, (name, len(v))
    return v
log, logl, alogh = arr('log'), arr('logL'), arr('alogh')
out = ['; ql_lltab.asm - GENERATED by tools/gen_lltab.py (do not edit): log, logL and alogh tables interleaved, 4 bytes per entry (log, logL, alogh, 0).',
       '\t.globl\t_ql_lltab', '\t.data', '_ql_lltab:']
for i in range(256):
    out.append('\t.dc.b\t%d,%d,%d,0' % (log[i], logl[i], alogh[i]))
open('src/ql_lltab.asm', 'w').write('\n'.join(out) + '\n')
print('src/ql_lltab.asm:', len(out) - 4, 'entradas')
