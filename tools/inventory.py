#!/usr/bin/env python3
"""Inventory of the reference source's routines and their port status.
Reads the headers ';       Name: X' / ';   Category: Y' / ';    Summary: Z' of elite-source.asm and the list
tools/ported.txt (one line per ported routine: NAME  C_function  state, state = verificada | sin-verificar | propia).
Generates docs/INVENTARIO.md. The reference source is not included in the project (see tools/README_ref.txt)."""
import os, re, sys
src = os.environ.get("ELITE_SRC", os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "ref", "moxon-appleII", "1-source-files", "main-sources"))
text = open(os.path.join(src, "elite-source.asm"), encoding="latin-1").read().split("\n")
ported = {}
for ln in open("tools/ported.txt"):
    ln = ln.split("#")[0].strip()
    if not ln: continue
    p = ln.split()
    ported[p[0]] = (p[1] if len(p) > 1 else "", p[2] if len(p) > 2 else "sin-verificar", " ".join(p[3:]))   # C function, state, note
rows = []
i = 0
while i < len(text):
    m = re.match(r"^;\s+Name: (\S+)(.*)$", text[i])
    if m:
        name, extra = m.group(1), m.group(2).strip()
        cat = summ = ""
        for j in range(i, min(i + 8, len(text))):
            c = re.match(r"^;\s+Category: (.*)$", text[j])
            s = re.match(r"^;\s+Summary: (.*)$", text[j])
            if c: cat = c.group(1).strip()
            if s: summ = s.group(1).strip()
        rows.append((name, extra, cat, summ))
    i += 1
seen = {}
out = []
for name, extra, cat, summ in rows:
    if name in seen: continue          # multi-part routines: a single row
    seen[name] = 1
    out.append((name, cat, summ))
tot = len(out)
def st(n): return ported[n][1] if n in ported else ""
VERIF = ("verificada",)
PEND_V = ("transcripcion", "sin-verificar", "propia")
def count(items):
    d = dict(total=len(items), ver=0, pv=0, nn=0, pi=0, nv=0)
    for n in items:
        s = st(n)
        if s in VERIF: d["ver"] += 1
        elif s in PEND_V: d["pv"] += 1
        elif s == "no-verificable": d["nv"] += 1
        elif s == "no-necesaria": d["nn"] += 1
        else: d["pi"] += 1                       # empty or partial
    d["port"] = d["ver"] + d["pv"] + d["nv"]
    return d
bycat = {}
for n, c, s in out:
    bycat.setdefault(c or "(no category)", []).append((n, s))
allc = count([n for n, c, s in out])
md = ["# Routine inventory (Elite Apple II -> Elite QL)", "",
      "Generated by `tools/inventory.py` from the reference source (Mark Moxon, Elite Apple II) and `tools/ported.txt`. Not edited by hand: change `tools/ported.txt` and run `python3 tools/inventory.py`.", "",
      "## Summary", "",
      "- Routines in the source: **%d**" % allc["total"],
      "- **Ported** (with the C function that covers them): **%d**, of which verified against the 6502: %d, **not verifiable** (they depend on Apple II hardware or on own screens; not requested again): %d and pending verification: %d" % (allc["port"], allc["ver"], allc["nv"], allc["pv"]),
      "- **Not needed** in the QL version (loader, copy protection, DOS RWTS, HGR tables, utilities the C compiler provides, etc.): **%d**" % allc["nn"],
      "- **Not ported** (pending implementation, partial ones included): **%d**" % allc["pi"],
      "", "Check: total = ported + not needed + not ported (%d = %d + %d + %d)." % (allc["total"], allc["port"], allc["nn"], allc["pi"]), "",
      "| Area | Total | Ported | Of which verified | Not verifiable | Not needed | Pending verification | Pending implementation |",
      "|---|---:|---:|---:|---:|---:|---:|---:|"]
for cat in sorted(bycat):
    c = count([n for n, s in bycat[cat]])
    md.append("| %s | %d | %d | %d | %d | %d | %d | %d |" % (cat, c["total"], c["port"], c["ver"], c["nv"], c["nn"], c["pv"], c["pi"]))
md.append("| **Total** | **%d** | **%d** | **%d** | **%d** | **%d** | **%d** | **%d** |" % (allc["total"], allc["port"], allc["ver"], allc["nv"], allc["nn"], allc["pv"], allc["pi"]))
md += ["", "Columns: *Ported* = verified + not verifiable + pending verification (includes own equivalents); *Not verifiable* = ported routines with no comparable equivalent in the original (state no-verificable: not requested in verification rounds); *Pending verification* = states transcripcion, sin-verificar and propia; *Pending implementation* = not ported or partial.", "",
       "## Routines not ported, by area", ""]
for cat in sorted(bycat):
    pend = [n + (" (partial)" if st(n) == "parcial" else "") for n, s in bycat[cat] if st(n) in ("", "parcial")]
    if pend: md.append("- **%s** (%d): %s" % (cat, len(pend), ", ".join("`%s`" % p if "(" not in p else "`%s` (partial)" % p.split(" ")[0] for p in pend)))
md += ["", "## States", "",
       "**verificada** (verified) = compared with the original 6502 (emulator); **transcripcion** (transcription) = compared with an own literal transcription of the 6502 (emulator missing); **sin-verificar** (unverified) = ported, noted in PENDIENTES.md; **propia** (own) = own substitute or equivalent (the C function covers what the routine did, in another form); **parcial** (partial) = a reduced version exists and part is missing (counts as pending implementation); **no-verificable** (not verifiable) = ported, but cannot be compared with the 6502 (it depends on Apple II hardware, such as text mode, or on the port's own screens): left out of the pending verifications; **no-necesaria** (not needed) = not needed in the QL version (the note says why); empty = not ported.", ""]
for cat in sorted(bycat):
    items = bycat[cat]
    c = count([n for n, s in items])
    md.append("## %s (%d ported of %d%s%s)" % (cat, c["port"], c["total"], (", %d not needed" % c["nn"]) if c["nn"] else "", (", %d not ported" % c["pi"]) if c["pi"] else ""))
    md.append("")
    md.append("| Routine | Summary | State | C | Note |")
    md.append("|---|---|---|---|---|")
    for n, s in items:
        if n in ported:
            md.append("| %s | %s | %s | %s | %s |" % (n, s, ported[n][1], (", ".join("`%s`" % f for f in ported[n][0].split(","))) if ported[n][0] != "-" else "", ported[n][2]))
        else:
            md.append("| %s | %s |  |  |  |" % (n, s))
    md.append("")
open("docs/INVENTARIO.md", "w").write("\n".join(md))
print("routines %d, ported %d (verified %d), not needed %d, not ported %d" % (allc["total"], allc["port"], allc["ver"], allc["nn"], allc["pi"]))
